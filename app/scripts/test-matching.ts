let pass = 0, choice = 0, fail = 0;
const misses: string[] = [];
for (const [t, want] of C) {
  const tri = findTriage(t, true);
  const d = decideGuide(t);
  if (d.guide?.id === want) pass++;
  else if (d.choices.some((g) => g.id === want)) choice++;
  else {
    fail++;
    const top = rankGuides(t).slice(0, 3).map((r) => `${r.guide.id}:${r.score.toFixed(1)}`).join(" ");
    misses.push(`✗ "${t}" want ${want} got ${d.guide?.id ?? (d.choices.map((c) => c.id).join("|") || "nothing")}${tri ? " [picker " + tri.id + "]" : ""}  top: ${top}`);
  }
}
